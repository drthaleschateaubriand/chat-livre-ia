// Teste de navegador (Playwright/Chromium headless) contra a PRODUÇÃO no GitHub Pages.
//   node tests/e2e.mjs [URL]   — screenshots em SHOTS_DIR (padrão /workspace/chat-livre-ia-private/screens)
// Obs.: usa o motor Chromium com perfil/viewport de iPhone (não é o WebKit real do iOS).
import { chromium, devices } from "playwright";
import { mkdirSync } from "node:fs";
import { OWNER_FILE, call, check, cleanupTestUsers, register, summary } from "./lib.mjs";
import { readFileSync } from "node:fs";

const URL = process.argv[2] ?? "https://drthaleschateaubriand.github.io/chat-livre-ia/";
const DIR = process.env.SHOTS_DIR ?? "/workspace/chat-livre-ia-private/screens";
mkdirSync(DIR, { recursive: true });
const section = (t) => console.log(`\n▶ ${t}`);
const browser = await chromium.launch();
const iphone = { ...devices["iPhone 13"], viewport: { width: 390, height: 844 }, locale: "pt-BR" };
const ctx = await browser.newContext({ ...iphone, permissions: ["clipboard-read", "clipboard-write"] });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error" && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
const shot = (name, p = page) => p.screenshot({ path: `${DIR}/${name}.png` });
const noHScroll = (p = page) => p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1);

section("Carregamento e tela de login (iPhone 390x844)");
const resp = await page.goto(URL, { waitUntil: "networkidle" });
check("página carrega (HTTP 200)", resp.status() === 200);
check("título do app", (await page.title()) === "CHAT LIVRE IA");
await shot("01-login-iphone");
check("sem rolagem horizontal no iPhone", await noHScroll());
const fs = await page.$eval('[data-testid="code-input"]', (e) => parseFloat(getComputedStyle(e).fontSize));
check(`campo do código com fonte >= 16px (${fs}px; evita zoom no iOS)`, fs >= 16);
check("campo do código é numérico (inputmode)", (await page.getAttribute('[data-testid="code-input"]', "inputmode")) === "numeric");
const sw = await page.evaluate(async () => { await navigator.serviceWorker.ready; const r = await navigator.serviceWorker.getRegistration(); return r?.scope; });
check(`service worker registrado com escopo do subcaminho (${sw})`, sw === URL);
const man = await page.evaluate(async () => { const l = document.querySelector('link[rel="manifest"]').href; const r = await fetch(l); const j = await r.json(); return { ok: r.ok, href: l, scope: j.scope, icons: j.icons.length }; });
check("manifest acessível com ícones", man.ok && man.icons >= 4, JSON.stringify(man));
const iconOk = await page.evaluate(async () => (await fetch(new URL("icons/icon-512.png", document.baseURI))).ok);
check("ícone 512 acessível", iconOk);

section("App PRIVADO: sem criação de conta na interface");
check("não existe botão/aba 'Criar conta'", (await page.locator("text=Criar conta").count()) === 0 && (await page.locator('[data-testid="create-btn"]').count()) === 0);
check("não existe 'Gerar meu código'", (await page.locator("text=Gerar meu código").count()) === 0);
check("tela de login diz que o app é privado", /App privado/.test(await page.textContent("body")));
check("botão 'Entrar com QR code' presente", await page.isVisible('[data-testid="qr-login-btn"]'));
await shot("02-login-privado");

section("Login com código (usuário de TESTE criado pelo ADMIN; sem cadastro público)");
const T = await register();
const codeShown = T.json.code;
await page.fill('[data-testid="code-input"]', codeShown);
await page.click('[data-testid="login-btn"]');
await page.waitForSelector('[data-testid="composer"]', { timeout: 30000 });
await shot("04-chat-vazio");
check("entrou no chat com o código", true);

section("Conversa com IA real (streaming)");
await page.fill('[data-testid="composer"]', "Responda em português, em no máximo 2 frases: o que é o Pix?");
await page.click('[data-testid="send"]');
await page.waitForSelector('[data-testid="streaming"]', { timeout: 20000 }).catch(() => {});
await shot("05-streaming");
await page.waitForSelector('[data-testid="msg-assistant"]', { timeout: 120000 });
await page.waitForSelector('[data-testid="regenerate"]', { timeout: 60000 });
const ans = await page.textContent('[data-testid="msg-assistant"]');
check("resposta da IA exibida", ans.length > 20, ans.slice(0, 80));
const label = await page.textContent('[data-testid="msg-model"]');
check(`modelo que respondeu aparece discretamente (“${label?.trim()}”)`, /·/.test(label ?? ""));
await shot("06-resposta");
check("URL com rota hash da conversa", /#\/c\/[0-9a-f-]{36}/.test(page.url()));

section("Markdown: tabela e bloco de código");
await page.fill('[data-testid="composer"]', "Mostre uma tabela markdown com 3 linhas (país, capital) e depois um bloco de código python que imprime 'oi'.");
await page.click('[data-testid="send"]');
await page.waitForFunction(() => document.querySelectorAll('[data-testid="msg-assistant"]').length >= 2, null, { timeout: 120000 });
await page.waitForSelector('[data-testid="regenerate"]', { timeout: 60000 });
const hasTable = await page.locator('[data-testid="msg-assistant"] >> nth=1').locator("table").count();
const hasCode = await page.locator('[data-testid="msg-assistant"] >> nth=1').locator("pre").count();
check("tabela renderizada", hasTable >= 1);
check("bloco de código renderizado com botão copiar", hasCode >= 1 && (await page.locator("text=Copiar código").count()) >= 1);
await page.locator("text=Copiar código").first().click();
const clip = await page.evaluate(() => navigator.clipboard.readText()).catch(() => "");
check("botão copiar código copia o código", clip.length > 0, clip.slice(0, 40));
check("sem rolagem horizontal com tabela/código", await noHScroll());
await shot("07-markdown");

section("Barra lateral: renomear, fixar, pesquisar");
await page.click('[data-testid="menu-btn"]');
await page.waitForSelector('[data-testid="sidebar"]');
await shot("08-sidebar");
await page.click('[data-testid="conv-menu"]');
await page.click("text=Renomear");
await page.keyboard.press("Control+A");
await page.keyboard.type("Conversa sobre Pix");
await page.keyboard.press("Enter");
await page.waitForSelector("text=Conversa sobre Pix");
await page.click('[data-testid="conv-menu"]');
await page.click("text=Fixar");
await page.waitForSelector("text=📌 Fixadas");
check("renomear e fixar refletem na lista", true);
await page.fill('[data-testid="search"]', "capital");
await page.waitForSelector('[data-testid="conv-item"]');
check("pesquisa no histórico encontra a conversa", (await page.locator('[data-testid="conv-item"]').count()) >= 1);
await shot("09-pesquisa");
await page.fill('[data-testid="search"]', "");

section("Recarregar a página: histórico persiste");
await page.reload({ waitUntil: "networkidle" });
await page.waitForSelector('[data-testid="msg-assistant"]', { timeout: 30000 });
check("depois de recarregar, as mensagens voltam do servidor", (await page.locator('[data-testid="msg-assistant"]').count()) >= 2);

section("Ajustes (iPhone), tema escuro");
await page.click('[data-testid="menu-btn"]');
await page.click('[data-testid="settings-btn"]');
await page.waitForSelector('[data-testid="settings"]');
await page.click("text=Escuro");
await shot("10-ajustes-aparencia-escuro");
check("tema escuro aplicado", await page.evaluate(() => document.documentElement.classList.contains("dark")));
await page.click("button:has-text('Modelos')");
await page.waitForSelector('[data-testid="provider-pollinations"]');
const gtxt = await page.textContent('[data-testid="provider-groq"]');
check("Groq aparece como 'não configurado'", /não configurado/.test(gtxt));
check("Pollinations aparece como ativo", /ativo/.test(await page.textContent('[data-testid="provider-pollinations"]')));
await shot("11-ajustes-modelos");
await page.click("button:has-text('Memória')");
await page.fill('[data-testid="memory-input"]', "Prefiro respostas curtas");
await page.click('[data-testid="memory-add"]');
await page.waitForSelector("text=Prefiro respostas curtas");
await shot("12-ajustes-memoria");
await page.click("button:has-text('Dispositivos')");
await page.waitForSelector('[data-testid="device"]');
await shot("13-ajustes-dispositivos");
await page.keyboard.press("Escape");
await page.click('button[aria-label="Fechar"]');

section("Seletor de modelo");
await page.click('[data-testid="model-picker"]');
await page.waitForSelector("text=Automático ✨");
check("seletor lista 'não configurado' para provedores sem chave", (await page.locator("text=não configurado").count()) >= 3);
await shot("14-seletor-modelos");
await page.keyboard.press("Escape");
await page.mouse.click(300, 400);

section("Segundo dispositivo (outro contexto) com o mesmo código");
const ctx2 = await browser.newContext({ ...devices["Pixel 7"], locale: "pt-BR" });
const p2 = await ctx2.newPage();
await p2.goto(URL, { waitUntil: "networkidle" });
await p2.fill('[data-testid="code-input"]', codeShown.replace(/(\d{4})(?=\d)/g, "$1-"));
await p2.click('[data-testid="login-btn"]');
await p2.waitForSelector('[data-testid="composer"]', { timeout: 30000 });
await p2.click('[data-testid="menu-btn"]').catch(() => {});
await p2.waitForSelector("text=Conversa sobre Pix", { timeout: 20000 });
check("segundo dispositivo vê a conversa renomeada", true);
await p2.click("text=Conversa sobre Pix");
await p2.waitForSelector('[data-testid="msg-assistant"]', { timeout: 20000 });
check("segundo dispositivo carrega o histórico", (await p2.locator('[data-testid="msg-assistant"]').count()) >= 2);
await shot("15-segundo-dispositivo-android", p2);
check("sem rolagem horizontal (Android 412px)", await noHScroll(p2));
// sincronização: dispositivo 1 envia, dispositivo 2 vê ao focar/polling
await page.fill('[data-testid="composer"]', "Responda apenas: sincronizado.");
await page.click('[data-testid="send"]');
await page.waitForFunction(() => document.querySelectorAll('[data-testid="msg-assistant"]').length >= 3, null, { timeout: 120000 });
await p2.evaluate(() => window.dispatchEvent(new Event("focus")));
await p2.waitForFunction(() => document.querySelectorAll('[data-testid="msg-assistant"]').length >= 3, null, { timeout: 30000 });
check("sincronização: mensagem enviada no dispositivo 1 aparece no 2 (refetch ao focar)", true);
await ctx2.close();

section("Desktop 1280x800");
const ctx3 = await browser.newContext({ viewport: { width: 1280, height: 800 }, locale: "pt-BR" });
const p3 = await ctx3.newPage();
await p3.goto(URL, { waitUntil: "networkidle" });
await shot("16-desktop-login", p3);
await p3.fill('[data-testid="code-input"]', codeShown);
await p3.click('[data-testid="login-btn"]');
await p3.waitForSelector('[data-testid="composer"]');
await p3.click("text=Conversa sobre Pix");
await p3.waitForSelector('[data-testid="msg-assistant"]');
await shot("17-desktop-chat", p3);
check("desktop: barra lateral fixa visível", await p3.isVisible('[data-testid="sidebar"]'));
await ctx3.close();

section("Ajustes → Dados: sem exclusão de conta (app privado)");
await page.click('[data-testid="menu-btn"]');
await page.click('[data-testid="settings-btn"]');
await page.click("button:has-text('Dados')");
await shot("18-dados-privado");
check("aviso 'App privado' presente e SEM botão de excluir conta", (await page.isVisible('[data-testid="private-note"]')) && (await page.locator("text=Excluir minha conta").count()) === 0);

section("DONO REAL: login pela interface com o código de owner_code.txt (somente leitura)");
const ownerCode = readFileSync(OWNER_FILE, "utf8").trim();
const ctxO = await browser.newContext({ ...iphone });
const pO = await ctxO.newPage();
await pO.goto(URL, { waitUntil: "networkidle" });
await pO.fill('[data-testid="code-input"]', ownerCode);
await pO.click('[data-testid="login-btn"]');
await pO.waitForSelector('[data-testid="composer"]', { timeout: 30000 });
await shot("25-dono-logado-iphone", pO);
check("o código do dono em owner_code.txt entra no app em produção (UI)", true);
const ownerSess = JSON.parse(await pO.evaluate(() => localStorage.getItem("cli.session")));
await call("auth", "logout", {}, ownerSess.access);
await ctxO.close();

await cleanupTestUsers();
check("sem erros de JavaScript no console", errors.length === 0, errors.slice(0, 3).join(" | "));
await browser.close();
summary();
